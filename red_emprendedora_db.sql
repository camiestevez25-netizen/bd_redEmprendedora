CREATE DATABASE red_emprendedora_db
    WITH
    OWNER = postgres
    ENCODING = 'UTF8'
    LC_COLLATE = 'Spanish_Spain.1252'
    LC_CTYPE = 'Spanish_Spain.1252'
    LOCALE_PROVIDER = 'libc'
    TABLESPACE = pg_default
    CONNECTION LIMIT = -1
    IS_TEMPLATE = False;

CREATE TABLE USUARIO (
    ID_USUARIO INT PRIMARY KEY AUTO_INCREMENT NOT NULL,
    NOMBRE VARCHAR(50) NOT NULL,
    EMAIL VARCHAR(50) NOT NULL,
    TELEFONO VARCHAR(15) NOT NULL,
    DIRECCION VARCHAR(50) NOT NULL,
    CONTRASENA VARCHAR(50) NOT NULL,
    ID_USUARIO_ROL CONSTRAINT FK_USUARIO_ROL REFERENCES USUARIO_ROL(ID_USUARIO_ROL)
    ID_EVENTO CONSTRAINT FK_EVENTO_USUARIO REFERENCES EVENTO(ID_EVENTO)
    ID_LOCALIDAD CONSTRAINT FK_LOCALIDAD_USUARIO REFERENCES LOCALIDAD(ID_LOCALIDAD)
    NOMBRE_EMPRENDIMIENTO VARCHAR(100),
    TIPO_EMPRENDIMIENTO VARCHAR(100),
    INSTAGRAM VARCHAR(100)
);
CREATE TABLE EVENTO (
    ID_EVENTO INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR (50) NOT NULL,
    FECHA_INICIO VARCHAR (25) NOT NULL,
    FECHA_FIN VARCHAR (25) NOT NULL,
    ESTADO VARCHAR (50) NOT NULL,
    PRECIO_ENTRADA NUMERIC(10, 2) NOT NULL,
    METROS_CUADRADOS VARCHAR (25) NOT NULL
    ID_LOCALIDAD INT CONSTRAINT FK_EVENTO_LOCALIDAD REFERENCES LOCALIDAD(ID_LOCALIDAD),
    ID_USUARIO INT CONSTRAINT FK_EVENTO_USUARIO REFERENCES USUARIO(ID_USUARIO)
); 


CREATE TABLE stand(
    ID_STAND  integer NOT NULL ,
    ID_EVENTO integer NOT NULL ,
    ID_USUARIO  integer NOT NULL,
    COSTO_STAND  DECIMAL(10,2) ,
    ESTADO_STAND  integer NOT NULL, 
    NUMERO_STAND  integer NOT NULL
)
